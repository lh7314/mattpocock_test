#!/usr/bin/env python3
"""Generate worked output examples (markdown) for docs/10 from the validated rule engine."""
import io, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "prototype"))
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
from rules_v1 import AnalysisInput, KeyFactor, match_sku, finalise  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def mk(**kw):
    return AnalysisInput(**{k: KeyFactor(k, file_value=v) for k, v in kw.items()})


def fmt(x):
    return f"{x:.1f}".rstrip("0").rstrip(".") if isinstance(x, float) else str(x)


def worked(title, inp, risk=0.0, extra=None, note=""):
    r = match_sku(inp)
    out = [f"\n### {title}", ""]
    dims = " | ".join(f"{k}={f.effective}" for k, f in inp.factors().items())
    out.append(f"输入：`{dims}`  {note}")
    out.append("")
    out.append(f"- SKU 状态：**{r['state']}**，推荐 = {r.get('recommended')}，范围 = {r.get('range')}")
    if r.get("missing_key_factors"):
        out.append(f"- 请补充：{', '.join(r['missing_key_factors'])}")
    skus = [r["recommended"]] if r.get("recommended") else (list(r.get("range") or []))
    rows = []
    for s in skus:
        f = finalise(inp, s, risk_pct=risk)
        if extra:
            f["conditional_increment"] = extra
            f["recommended_total"] = f["base_demand"] + extra + f["confirmed_reuse_adjustment"] + f["risk_reserve"]
        rows.append(f)
        out.append(f"- SKU{s}：base={fmt(f['base_demand'])}  FVT={fmt(f['fvt'])}  SIT={fmt(f['sit'])}  "
                   f"cond={fmt(f['conditional_increment'])}  reuse={fmt(f['confirmed_reuse_adjustment'])}  "
                   f"risk={f['risk_reserve']:.3f}  →  **recommended={f['recommended_total']:.3f}**")
    if len(rows) > 1:
        lo, hi = rows[0], rows[-1]
        out.append(f"- 范围输出：Total **{fmt(lo['recommended_total'])} – {fmt(hi['recommended_total'])}**"
                   f"，FVT **{fmt(lo['fvt'])} – {fmt(hi['fvt'])}**，SIT **{fmt(lo['sit'])} – {fmt(hi['sit'])}**")
    return "\n".join(out), (skus, rows)


L = ["# Worked examples generated by `prototype/rules_v1.py`", ""]

blocks = [
    ("EX-1 单一推荐：4 SKU（无附加项）", mk(cpu=3, gpu=2, panel=2, ssd=2, mem=2), 0.0, None),
    ("EX-2 单一推荐：4 SKU（+1.0 额外需求 / −0.5 已确认复用 / +5% 风险预留）",
     mk(cpu=3, gpu=2, panel=2, ssd=2, mem=2), 0.05, 1.0),
    ("EX-3 范围推荐：仅知 CPU=3（4 个维度请补充）", mk(cpu=3), 0.0, None),
    ("EX-4 单一推荐：2 SKU", mk(cpu=1, gpu=1, panel=1, ssd=1, mem=1), 0.0, None),
    ("EX-5 单一推荐：6 SKU", mk(cpu=5, gpu=3, panel=3, ssd=2, mem=3), 0.0, None),
    ("EX-6 竞争案例：cpu2/gpu1/panel1/ssd2/mem2", mk(cpu=2, gpu=1, panel=1, ssd=2, mem=2), 0.0, None),
    ("EX-7 缺失维度：Panel 请补充", mk(cpu=3, gpu=2, ssd=2, mem=2), 0.0, None),
]
for title, inp, risk, extra in blocks:
    txt, _ = worked(title, inp, risk, extra)
    L.append(txt)

# full function-level detail for EX-2
_, (skus, rows) = worked("detail", mk(cpu=3, gpu=2, panel=2, ssd=2, mem=2), 0.05, None)
sku = skus[0]
f = finalise(mk(cpu=3, gpu=2, panel=2, ssd=2, mem=2), sku, 0.0)
L.append("\n---\n\n## EX-2 Function/Phase 明细（4 SKU，base 口径）\n")
L.append("| Function | Category | Phase | 费率/SKU | SKU | Base | 状态备注 |")
L.append("|---|---|---|---|---|---|---|")
for r in sorted(f["rows"], key=lambda x: (x["category"], x["function"], x["phase"])):
    st = (r["status_note"] or "").replace("\n", " ")[:38]
    L.append(f"| {r['function']} | {r['category']} | {r['phase']} | {r['per_sku_rate']} | {r['sku_qty']} | "
             f"{fmt(r['base_demand'])} | {st} |")
L.append(f"\n合计 Base = **{fmt(f['base_demand'])}**（FVT {fmt(f['fvt'])} + SIT {fmt(f['sit'])}）")
L.append("\nCategory 汇总：" + ", ".join(f"{k}={fmt(v)}" for k, v in f["by_category"].items()))

(ROOT / "artifacts/validation/worked_examples.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("\n".join(L))
